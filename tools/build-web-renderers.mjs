// Produce the renderer bundles the web-server serves.
//
// The web image needs `<app>/out/renderer/` for every app in
// `apps/web-server/src/common/paths.ts`'s APPS list — the server routes
// `/docs/`, `/sheets/`, … straight into them, and a missing one is a 404 or a
// blank editor in production. Nothing produced them: the image build ran
// `npm run build -w @genoffice/docs` and nothing else, so six of the seven
// apps were simply absent from every released image (sdk1.md §11.125).
//
// `npm run build:all` is not the right producer for an image either: it also
// builds `@genoffice/cli` and, for sheets, runs `cargo build --release`, which
// a Node-only build stage has no toolchain for. That native sidecar is a
// desktop concern — the sheets renderer reaches the xlsx engine over HTTP
// (`@genoffice/ipc-bridge/web-native`), not through it — so this script runs
// `electron-vite build` directly in each app and skips the native step. The
// renderer configs contain no reference to the cargo output.
//
// Sequential, and fail-fast: a non-zero exit stops the run rather than
// shipping an image with a subset of the editors.
//
// Requires `npm run build:sdk` to have run: the apps import
// `@genoffice/web-sdk` subpaths that resolve to `apps/sdk/dist`. The check
// below says so rather than letting Vite fail with a bare resolve error.

import { spawnSync } from 'node:child_process'
import { existsSync, readFileSync } from 'node:fs'
import { createRequire } from 'node:module'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')

/** Must match APPS in apps/web-server/src/common/paths.ts. */
const APPS = ['docs', 'sheets', 'slides', 'pdf', 'markdown', 'html', 'shell']

const require = createRequire(import.meta.url)

/** Locate electron-vite's entry script from an app directory (hoisted or not). */
function electronViteBin(appDir) {
  const pkgPath = require.resolve('electron-vite/package.json', { paths: [appDir] })
  const pkg = JSON.parse(readFileSync(pkgPath, 'utf8'))
  const rel = typeof pkg.bin === 'string' ? pkg.bin : pkg.bin?.['electron-vite']
  if (!rel) throw new Error(`${pkgPath} declares no "electron-vite" bin`)
  return resolve(dirname(pkgPath), rel)
}

const only = process.argv.slice(2)
const selected = only.length > 0 ? APPS.filter((a) => only.includes(a)) : APPS
if (selected.length === 0) {
  console.error(`[renderers] no app matched ${JSON.stringify(only)}; known apps: ${APPS.join(', ')}`)
  process.exit(1)
}

// The apps import `@genoffice/web-sdk/...` subpaths, which resolve through
// node_modules to `apps/sdk/dist/*` — `apps/docs` does it from the renderer
// (`src/renderer/web-bridge.ts`, `App.tsx`, `ai/AiPanel.tsx`), and its
// electron-vite config aliases only the `@genoffice/*` packages that ship raw
// TS source, not the SDK. Without the SDK's dist the renderer build dies
// inside Vite with a resolve error that names no cause; check the manifest
// entry output first so the failure says what to run. The manifest is
// generated by `apps/sdk/scripts/build.mjs` and lists exactly what it emits.
{
  const dist = resolve(root, 'apps', 'sdk', 'dist')
  const manifestPath = resolve(root, 'apps', 'sdk', 'scripts', 'sdk-entries.json')
  let entries
  try {
    entries = JSON.parse(readFileSync(manifestPath, 'utf8')).entries
  } catch (err) {
    console.error(`[renderers] cannot read ${manifestPath}: ${err.message}`)
    process.exit(1)
  }
  const missing = entries
    .map((e) => `${e.out}.mjs`)
    .filter((f) => !existsSync(resolve(dist, f)))
  if (missing.length > 0) {
    console.error(
      `[renderers] the SDK is not built: ${missing.length} of ${entries.length} entries are absent from apps/sdk/dist (${missing
        .slice(0, 6)
        .join(', ')}${missing.length > 6 ? ', …' : ''})`,
    )
    console.error('[renderers] the apps import @genoffice/web-sdk subpaths from there; run this first:')
    console.error('[renderers]   npm run build:sdk')
    process.exit(1)
  }
}

for (const app of selected) {
  const appDir = resolve(root, 'apps', app)
  const bin = electronViteBin(appDir)
  console.log(`[renderers] ${app}: electron-vite build`)
  const res = spawnSync(process.execPath, [bin, 'build'], { stdio: 'inherit', cwd: appDir })
  if (res.status !== 0) {
    console.error(
      `[renderers] ${app} failed (exit ${res.status}); apps/${app}/out/renderer would be missing or stale`,
    )
    process.exit(1)
  }
}

console.log(`[renderers] built out/renderer for ${selected.length} app(s) →`, 'apps/*/out')
