#!/usr/bin/env node
/**
 * gen-ipc-docs.mjs — scan `registerHandle` calls across the web-server
 * capability directories and emit a Markdown reference.
 *
 * Output: `apps/web-server/IPC_CHANNELS.md` (one section per channel,
 * grouped by capability directory).
 *
 * Usage:
 *   node tools/gen-ipc-docs.mjs                    # writes to apps/web-server/IPC_CHANNELS.md
 *   node tools/gen-ipc-docs.mjs --check            # exits 1 if the file would change
 *   node tools/gen-ipc-docs.mjs --out docs/api/ipc-channels.md
 *
 * The generator is intentionally simple: it grep-finds every
 * `registerHandle('channel:name', ...)` call and pulls the first
 * comment line above it as the docstring. No AST parsing, no plugin
 * system — change it when the source shape changes.
 */

import { readFileSync, writeFileSync, existsSync, readdirSync, statSync } from 'node:fs'
import { join, relative, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const __filename = fileURLToPath(import.meta.url)
const repoRoot = resolve(__filename, '..', '..')
const capabilityRoot = join(repoRoot, 'apps', 'web-server', 'src')

const args = process.argv.slice(2)
const check = args.includes('--check')
const outIdx = args.indexOf('--out')
const outPath = outIdx >= 0 ? resolve(args[outIdx + 1]) : join(repoRoot, 'apps', 'web-server', 'IPC_CHANNELS.md')

/** Walk the capability tree and yield every .ts file path. */
function* walkTs(dir) {
  for (const entry of readdirSync(dir)) {
    const p = join(dir, entry)
    const s = statSync(p)
    if (s.isDirectory()) {
      if (entry === 'node_modules' || entry.startsWith('.')) continue
      yield* walkTs(p)
    } else if (s.isFile() && p.endsWith('.ts') && !p.endsWith('.d.ts')) {
      yield p
    }
  }
}

/**
 * Extract `registerHandle('channel:name', ...)` calls from a file along
 * with the docstring comment immediately above each call.
 */
function extractChannels(filePath) {
  const text = readFileSync(filePath, 'utf-8')
  const lines = text.split(/\r?\n/)
  const out = []
  for (let i = 0; i < lines.length; i++) {
    const line = lines[i]
    const m = /registerHandle\(\s*['"]([^'"]+)['"]/.exec(line)
    if (!m) continue
    const channel = m[1]
    // Walk backward over blank/comment lines to collect the JSDoc above.
    const docLines = []
    let j = i - 1
    while (j >= 0 && (lines[j].trim() === '' || lines[j].trim().startsWith('*') || lines[j].trim().startsWith('//'))) {
      if (lines[j].trim().startsWith('*') || lines[j].trim().startsWith('//')) {
        docLines.unshift(lines[j].trim().replace(/^\*\s?/, '').replace(/^\/\/\s?/, ''))
      }
      j--
    }
    out.push({ channel, docstring: docLines.join(' ').trim(), line: i + 1 })
  }
  return out
}

function main() {
  if (!existsSync(capabilityRoot)) {
    console.error(`capability root not found: ${capabilityRoot}`)
    process.exit(2)
  }
  /** channel → { docstring, files: [{path, line}] } */
  const all = new Map()
  for (const file of walkTs(capabilityRoot)) {
    const rel = relative(capabilityRoot, file)
    const entries = extractChannels(file)
    for (const e of entries) {
      const key = e.channel
      if (!all.has(key)) all.set(key, { docstring: e.docstring, files: [] })
      const bucket = all.get(key)
      if (!bucket.docstring && e.docstring) bucket.docstring = e.docstring
      bucket.files.push({ path: rel, line: e.line })
    }
  }

  const entries = [...all.entries()].sort((a, b) => a[0].localeCompare(b[0]))

  const lines = []
  lines.push('# IPC Channel Reference')
  lines.push('')
  lines.push(`> Generated by \`tools/gen-ipc-docs.mjs\` — do not edit by hand.`)
  lines.push(`> ${entries.length} channels across ${new Set([...all.values()].flatMap((v) => v.files.map((f) => f.path.split('/')[0]))).size} capability directories.`)
  lines.push('')
  lines.push('Each section lists the channel name, a one-line description (when the source carries a comment), and the file that registers it.')
  lines.push('')

  let currentArea = ''
  for (const [channel, info] of entries) {
    const area = info.files[0]?.path.split('/')[0] ?? 'misc'
    if (area !== currentArea) {
      lines.push(`## ${area}`)
      lines.push('')
      currentArea = area
    }
    const desc = info.docstring || '_no docstring_'
    lines.push(`### \`${channel}\``)
    lines.push('')
    lines.push(desc)
    lines.push('')
    for (const f of info.files) {
      lines.push(`- \`apps/web-server/src/${f.path}:${f.line}\``)
    }
    lines.push('')
  }

  const rendered = lines.join('\n')

  if (check) {
    const existing = existsSync(outPath) ? readFileSync(outPath, 'utf-8') : ''
    if (existing !== rendered) {
      console.error(`IPC docs are stale: ${outPath} would change. Run \`node tools/gen-ipc-docs.mjs\` to refresh.`)
      process.exit(1)
    }
    console.log(`IPC docs up to date (${entries.length} channels)`)
    return
  }

  writeFileSync(outPath, rendered, 'utf-8')
  console.log(`wrote ${entries.length} channels → ${relative(process.cwd(), outPath)}`)
}

main()
